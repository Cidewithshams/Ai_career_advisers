import gradio as gr
import json
import os
from groq import Groq
from datetime import datetime

from getpass import getpass

GROQ_API_KEY = ("GROQ_API_KEY")

client = Groq(api_key=GROQ_API_KEY)

print("Groq API connected successfully!")

MODEL_NAME = "openai/gpt-oss-120b"

def ask_ai(prompt):

    response = client.chat.completions.create(
        model=MODEL_NAME,
        messages=[
            {
                "role": "system",
                "content": """
                You are a professional AI Career Advisor.
                Give practical, realistic and personalized
                career guidance to users.
                Use clear headings and actionable advice.
                Do not guarantee jobs or salaries.
                """
            },
            {
                "role": "user",
                "content": prompt
            }
        ],
        temperature=0.7,
        max_tokens=2000
    )

    return response.choices[0].message.content

def generate_career_advice(
    name,
    education,
    interests,
    skills,
    experience,
    goal,
    task
):

    if not all([name, education, interests, skills, goal]):
        return "Please complete all required profile fields."

    prompt = f"""
    Analyze this user's career profile.

    Name: {name}
    Education: {education}
    Interests: {interests}
    Current Skills: {skills}
    Experience: {experience}
    Career Goal: {goal}

    Requested Analysis: {task}

    Give detailed, practical and personalized advice.

    Include:
    - Clear recommendations
    - Skills to improve
    - Suggested learning resources/topics
    - Practical projects
    - Realistic next steps

    Use professional headings and bullet points.
    Avoid guaranteeing employment or income.
    """

    try:
        return ask_ai(prompt)

    except Exception as e:
        return f"AI Error: {str(e)}"

custom_css = """
.gradio-container {
    max-width: 1150px !important;
    margin: auto !important;
}
"""

with gr.Blocks(
    theme=gr.themes.Soft(),
    css=custom_css,
    title="AI Career Advisor"
) as demo:

    gr.Markdown("""
    # 🚀 AI Career Advisor
    ### Discover your potential. Build your future.

    Your personal AI-powered career guidance platform.
    """)

    with gr.Tab("👤 My Profile"):

        name = gr.Textbox(label="Full Name")

        education = gr.Dropdown(
            ["Matric", "Intermediate", "Bachelor's",
             "Master's", "Other"],
            label="Education"
        )

        interests = gr.Textbox(
            label="Career Interests",
            placeholder="AI, Python, Web Development..."
        )

        skills = gr.Textbox(
            label="Current Skills",
            placeholder="Python, HTML, CSS..."
        )

        experience = gr.Dropdown(
            ["No Experience", "Beginner",
             "Intermediate", "Experienced"],
            label="Experience Level"
        )

        goal = gr.Textbox(
            label="Your Career Goal",
            placeholder="Example: Become an AI Engineer"
        )

    with gr.Tab("🧠 Career Analysis"):

        task = gr.Radio(
            [
                "Career Recommendations",
                "Skill Gap Analysis",
                "Learning Roadmap",
                "Job Role Explorer"
            ],
            label="Select Analysis",
            value="Career Recommendations"
        )

        analyze_btn = gr.Button(
            "✨ Generate Career Analysis",
            variant="primary"
        )

        output = gr.Markdown()

        analyze_btn.click(
            fn=generate_career_advice,
            inputs=[
                name,
                education,
                interests,
                skills,
                experience,
                goal,
                task
            ],
            outputs=output
        )

    with gr.Tab("💬 AI Career Assistant"):

        question = gr.Textbox(
            label="Ask Your Career Question",
            placeholder="How can I become a Data Scientist?"
        )

        answer = gr.Markdown()

        chat_btn = gr.Button("Ask AI")

        def career_chat(q):
            if not q.strip():
                return "Please enter a question."

            return ask_ai(
                "Answer this career-related question clearly: " + q
            )

        chat_btn.click(
            career_chat,
            inputs=question,
            outputs=answer
        )

    gr.Markdown("""
    ---
    **AI Career Advisor** | Powered by Python, Gradio & Groq
    """)

demo.launch(share=True)
